    # ---------------------------------------------------------------- session wiring
    def attach(self, session: DebugSession):
        self.session = session
        self._regs, self._prev_regs = {}, {}
        self._mem_this_stop, self._mem_last_stop = {}, {}
        session.connect("connected", lambda *_: self._set_running(True))
        session.connect("stopped", self._on_stopped)
        session.connect("resumed", lambda *_: self._set_running(True))
        session.connect("ended", self._on_ended)
        self.state_label.set_text("Starting VICE…")

    def _set_running(self, running: bool):
        stepping = running and self.session is not None and self.session.stepping
        self.state_label.set_text("Stepping to the next C line…" if stepping else "Running" if running else "Stopped")
        editable = not running and self.session is not None
        for e in self.reg_entries.values():
            e.set_sensitive(editable)
        for b in self.flag_buttons:
            b.set_sensitive(editable)
        self.write_entry.set_sensitive(editable)
        self.memory.editable = editable
        self.buttons["continue"].set_sensitive(not running)
        self.buttons["pause"].set_sensitive(running)
        for k in ("into", "over", "out"):
            self.buttons[k].set_sensitive(not running)
        self.buttons["stop"].set_sensitive(True)

    def _on_ended(self, _s, reason: str):
        self.state_label.set_text(f"Ended: {reason}")
        for b in self.buttons.values():
            b.set_sensitive(False)
        for e in self.reg_entries.values():
            e.set_sensitive(False)
        for b in self.flag_buttons:
            b.set_sensitive(False)
        self.write_entry.set_sensitive(False)
        self.memory.editable = False
        if self.session:
            self.session.stop()
        self.session = None
        self.emit("show-source", "", 0)

    def do(self, key: str):
        s = self.session
        if not s:
            return
        m = s.monitor
        pc = self._regs.get("PC")
        if key == "pause" and s.stepping:
            s.cancel_step()                    # stops where it's got to
            return
        if key in ("into", "over") and not s.running and pc is not None and s.steps_by_c_line(pc):
            s.step_line(over=key == "over")    # in C: to the next line, not the next instruction
            return
        if key in ("into-instruction", "over-instruction"):
            key = key.split("-")[0]            # by instruction, even in C
        if key in ("continue", "into", "over") and pc in s.checkpoints and not s.running:
            opcode = (s.cmd(m.read_memory, pc, pc) or b"\0")[0]
            s.cmd(s.leave_breakpoint, pc)      # runs the instruction at the breakpoint
            if key == "into":
                return                         # that was the step
            if key == "over":
                if opcode == 0x20:             # it was a JSR: finish the subroutine too
                    s.cmd(m.step_out)
                return                         # "continue" goes on to resume below
        if key == "continue":
            s.cmd(m.resume)
        elif key == "pause":
            s.cmd(m.ping)  # any command stops VICE in the monitor
            s.running = False
            regs = s.cmd(m.get_registers)
            if regs:
                self._on_stopped(s, regs.get("PC", 0))
        elif key == "into":
            s.cmd(m.step, 1, False)
        elif key == "over":
            s.cmd(m.step, 1, True)
        elif key == "out":
            s.cmd(m.step_out)
        elif key == "stop":
            self._on_ended(s, "stopped by user")

    def _on_stopped(self, session, pc: int, snapshot: bool = True):
        """Show the machine's state. snapshot=False after an edit, so 'changed' still means
        changed since the program stopped."""
        self._set_running(False)
        m = session.monitor
        regs = session.cmd(m.get_registers) or {}
        if snapshot:
            self._prev_regs = dict(self._regs) if self._regs else dict(regs)
        self._regs = dict(regs)
        pc = regs.get("PC", pc)
        self._show_registers()
        self._show_code(session, pc)
        self._show_watches(session)
        self.refresh_memory(snapshot=snapshot)
        src = session.srcmap.get(pc)
        self.emit("show-source", src[0] if src else "", src[1] if src else 0)
        self._show_variables(session, pc, snapshot)

    # ---------------------------------------------------------------- C variables
    def set_c_program(self, program, sp_address: int = 0x02):
        """A C program's variables to show at each stop (cvars.CProgram), or None for assembler."""
        self.c_program, self.c_sp = program, sp_address
        self._var_values = {}
        self.vars_box.set_visible(program is not None)
        while (row := self.vars_list.get_row_at_index(0)) is not None:
            self.vars_list.remove(row)

    def _show_variables(self, session, pc: int, snapshot: bool = True):
        prog = self.c_program
        if prog is None:
            return
        m = session.monitor
        zp = session.cmd(m.read_memory, self.c_sp, self.c_sp + 1) or b"\0\0"
        sp = zp[0] | zp[1] << 8
        here = session.c_line_at(pc)
        at_line_start = here is not None and session.srcmap.get(pc) == here
        fn, variables = prog.variables(here, sp)
        if fn is None:
            self.vars_where.set_text("not in a C function: globals only")
        else:
            self.vars_where.set_text(f"in {fn.name}()" + ("" if at_line_start else
                                     " (between lines: locals may be off while a line is part-way through)"))
        # globals in one read where they're close together, the rest one by one
        cache: dict[int, int] = {}
        globs = [v for v in variables if v.group == "global" and v.address is not None]
        if globs:
            lo = min(v.address for v in globs)
            hi = max(v.address + v.size for v in globs) - 1
            if hi - lo < 0x2000:
                data = session.cmd(m.read_memory, lo, hi) or b""
                cache.update({lo + i: b for i, b in enumerate(data)})

        def read(addr: int, size: int) -> bytes:
            if all(addr + i in cache for i in range(size)):
                return bytes(cache[addr + i] for i in range(size))
            data = session.cmd(m.read_memory, addr, min(0xFFFF, addr + size - 1)) or b""
            cache.update({addr + i: b for i, b in enumerate(data)})
            return data

        while (row := self.vars_list.get_row_at_index(0)) is not None:
            self.vars_list.remove(row)
        last_group = None
        values = {}
        for v in variables:
            group = "Globals" if v.group == "global" else f"{fn.name}()" if fn else "Locals"
            if group != last_group:
                head = Gtk.Label(label=group, xalign=0, css_classes=["dim-label", "caption-heading"], margin_top=2)
                self.vars_list.append(Gtk.ListBoxRow(child=head, activatable=False))
                last_group = group
            data = b""
            if v.address is None:
                value = ""
            else:
                data = read(v.address, max(1, min(v.size, 256)))
                value = prog.show(v, data)
            key = (v.group, v.name)
            values[key] = value
            box = Gtk.Box(spacing=8, margin_start=6)
            box.append(Gtk.Label(label=v.name, xalign=0, width_chars=14, ellipsize=Pango.EllipsizeMode.END,
                                 css_classes=["monospace"]))
            box.append(Gtk.Label(label=v.type_name, xalign=0, width_chars=14, ellipsize=Pango.EllipsizeMode.END,
                                 css_classes=["dim-label", "caption"]))
            val = Gtk.Label(label=value or v.note, xalign=0, hexpand=True, ellipsize=Pango.EllipsizeMode.END,
                            selectable=bool(value), css_classes=["monospace"] if value else ["dim-label", "caption"],
                            tooltip_text=value or v.note or None)
            if value and self._var_values.get(key) and self._var_values[key] != value:
                val.add_css_class("warning")         # changed since the last stop, as registers are
            box.append(val)
            box.append(Gtk.Label(label=f"${v.address:04X}" if v.address is not None else "", width_chars=6,
                                 css_classes=["dim-label", "caption", "monospace"]))
            row = Gtk.ListBoxRow(child=box, activatable=v.address is not None,
                                 tooltip_text="Double-click to set it" if v.address is not None else None)
            row.var_address = v.address
            row.variable, row.data = v, data
            self.vars_list.append(row)
        if snapshot:
            self._var_values = values

    def _variable_activated(self, _list, row):
        """Double-click a variable: set its value (or show its bytes in the memory view)."""
        s, prog, v = self.session, self.c_program, getattr(row, "variable", None)
        if v is None or v.address is None or prog is None:
            return
        if not s or s.running:
            self.refresh_memory(v.address)
            return
        from ..cvars import edit_text, encode_value
        structs = prog.source.structs
        size = max(1, min(v.size, 256))
        dlg = Adw.AlertDialog(heading=f"Set {v.name}",
                              body=f"{v.type_name} at ${v.address:04X} ({size} byte{'s' if size != 1 else ''})")
        entry = Gtk.Entry(text=edit_text(v.ctype, row.data, structs), activates_default=True,
                          css_classes=["monospace"])
        hint = Gtk.Label(xalign=0, wrap=True, css_classes=["dim-label", "caption"], label=(
            "A number: decimal, $hex, 0x hex, %binary or 'c'" if v.ctype and not v.ctype.dims and not v.ctype.pointer
            and v.ctype.base not in ("struct", "union") else
            "An address ($C000) or NULL" if v.ctype and v.ctype.pointer and not v.ctype.dims else
            'Text in quotes ("hello"), or the items separated by commas' if v.ctype and v.ctype.dims else
            "The bytes in hex, e.g. 05 00 FE FF"))
        problem = Gtk.Label(xalign=0, wrap=True, css_classes=["error", "caption"], visible=False)
        box = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6)
        for w in (entry, hint, problem):
            box.append(w)
        dlg.set_extra_child(box)
        dlg.add_response("cancel", "Cancel")
        dlg.add_response("memory", "Show in Memory")
        dlg.add_response("set", "Set")
        dlg.set_default_response("set")
        dlg.set_response_appearance("set", Adw.ResponseAppearance.SUGGESTED)

        def check(*_):
            try:
                encode_value(v.ctype, entry.get_text(), size, structs)
            except ValueError as e:
                problem.set_text(str(e))
                problem.set_visible(True)
                dlg.set_response_enabled("set", False)
                return
            problem.set_visible(False)
            dlg.set_response_enabled("set", True)
        entry.connect("changed", check)
        check()

        def chosen(d, res):
            r = d.choose_finish(res)
            if r == "memory":
                self.refresh_memory(v.address)
            elif r == "set" and self.session is s:
                try:
                    self.set_variable(v, entry.get_text())
                except ValueError:
                    pass
        dlg.choose(self.get_root(), None, chosen)

    def set_variable(self, v, text: str) -> None:
        """Write a C variable's new value (as typed) into memory, and show it. ValueError if the text
        isn't a value of its type, or the program isn't stopped."""
        from ..cvars import encode_value
        s, prog = self.session, self.c_program
        if not s or s.running or prog is None or v.address is None:
            raise ValueError("Only while the program is stopped")
        data = encode_value(v.ctype, text, max(1, min(v.size, 256)), prog.source.structs)
        s.cmd(s.monitor.write_memory, v.address, data)
        self._show_variables(s, self._regs.get("PC", 0), snapshot=False)   # "changed" stays since the stop
        self.refresh_memory(v.address)

    def _show_watches(self, session):
        if not session.watches:
            self.watch_label.set_visible(False)
            return
        rows = []
        for name, addr, comment in session.watches:
            data = session.cmd(session.monitor.read_memory, addr, min(0xFFFF, addr + 1)) or b"\0\0"
            word = data[0] | (data[1] << 8 if len(data) > 1 else 0)
            rows.append(f"{name} ${addr:04X}: ${data[0]:02X} ({data[0]})  word ${word:04X}"
                        + (f"   {comment}" if comment else ""))
        self.watch_label.set_text("Watch  " + "\n       ".join(rows))
        self.watch_label.set_visible(True)

    def _show_registers(self):
        self._updating = True
        for name, digits in REGISTERS:
            e = self.reg_entries[name]
            v = self._regs.get(name, 0)
            e.set_text(f"{v:0{digits}X}")
            changed = name in self._prev_regs and self._prev_regs[name] != v
            if changed:
                e.add_css_class("warning")
            else:
                e.remove_css_class("warning")
        fl = self._regs.get("FL", 0)
        old = self._prev_regs.get("FL", fl)
        for i, b in enumerate(self.flag_buttons):
            bit = 1 << (7 - i)
            b.set_active(bool(fl & bit))
            if (fl ^ old) & bit:
                b.add_css_class("warning")
            else:
                b.remove_css_class("warning")
        self._updating = False

    def _show_code(self, session, pc: int):
        m = session.monitor
        start = max(0, pc - 16)
        mem = session.cmd(m.read_memory, start, min(0xFFFF, pc + 96)) or b""
        # Resync: disassemble from a point that lands exactly on PC.
        lines = None
        for back in range(0, 17):
            off = pc - start - back
            if off < 0:
                break
            cand = disassemble(mem[off:], pc - back, 40, session.symbols)
            if any(a == pc for a, _, _ in cand):
                lines = cand
                break
        lines = lines or disassemble(mem[pc - start:], pc, 40, session.symbols)
        buf = self.disasm.get_buffer()
        text, pc_line = [], 0
        for i, (a, hx, t) in enumerate(lines):
            label = session.symbols.get(a, "")
            if a == pc:
                pc_line = i
            text.append(f"{'>' if a == pc else ' '} {a:04X}  {hx:<9} {t:<24} {label}")
        buf.set_text("\n".join(text))
        ok, it = buf.get_iter_at_line(pc_line)
        if ok:
            end = it.copy()
            end.forward_to_line_end()
            buf.apply_tag(self.disasm_pc_tag, it, end)
            # A mark survives later changes to the buffer, unlike the iterator.
            buf.move_mark(self.disasm_pc_mark, it)
            GLib.idle_add(lambda: (self.disasm.scroll_mark_onscreen(self.disasm_pc_mark), False)[1])

    # ---------------------------------------------------------------- memory
    def _symbols_by_name(self) -> dict[str, int]:
        s = self.session
        return {name: addr for addr, name in s.symbols.items()} if s else {}

    def refresh_memory(self, base: int | None = None, snapshot: bool = False):
        s = self.session
        if not s or s.running:
            return
        if base is None:
            try:
                base = parse_address(self.mem_addr.get_text() or "0400", self._symbols_by_name())
            except ValueError_ as e:
                self.mem_status.set_text(str(e))
                return
        base = max(0, min(base, 0x10000 - 256))
        data = s.cmd(s.monitor.read_memory, base, base + 255) or b""
        if snapshot:
            self._mem_last_stop, self._mem_this_stop = self._mem_this_stop, {}
        for i, b in enumerate(data):
            self._mem_this_stop.setdefault(base + i, b)
        self.memory.set_data(base, data)
        # Compare with the previous stop; bytes never seen before count as unchanged.
        self.memory.previous = {a: self._mem_last_stop.get(a, self._mem_this_stop[a])
                                for a in range(base, base + len(data))}
        if self.mem_addr.get_text().strip().lower() not in self._symbols_by_name():
            self.mem_addr.set_text(f"{base:04X}")

    def _goto(self):
        try:
            addr = parse_address(self.mem_addr.get_text(), self._symbols_by_name())
        except ValueError_ as e:
            self.mem_status.set_text(str(e))
            return
        self.refresh_memory(addr)
        self.memory.cursor = addr
        self.memory.grab_focus()
        self._cursor_moved(self.memory, addr)

    def _cursor_moved(self, _h, addr: int):
        v = self.memory.value_at(addr)
        label = self.session.symbols.get(addr, "") if self.session else ""
        text = f"${addr:04X}" + (f" ({label})" if label else "")
        if v is not None:
            text += f" = ${v:02X}  {v}  %{v:08b}"
        self.mem_status.set_text(text + ("    type hex digits to change it" if self.memory.editable else ""))

    def _write(self, addr: int, data: bytes) -> bool:
        s = self.session
        if not s or s.running:
            return False
        if addr + len(data) > 0x10000:
            self.mem_status.set_text("That would write past $FFFF")
            return False
        try:
            s.monitor.write_memory(addr, data, side_effects=is_io(addr, len(data)))
        except (OSError, MonitorError) as e:
            self.mem_status.set_text(f"Couldn't write: {e}")
            return False
        # Refresh everything: the write may have changed code, the screen, or I/O registers.
        self._on_stopped(s, self._regs.get("PC", 0), snapshot=False)
        return True

    def _byte_edited(self, _h, addr: int, value: int):
        if self._write(addr, bytes([value])):
            self._cursor_moved(self.memory, self.memory.cursor)

    def _write_entered(self, entry):
        try:
            data = parse_bytes(entry.get_text(), self._symbols_by_name())
        except ValueError_ as e:
            self.mem_status.set_text(str(e))
            return
        addr = self.memory.cursor
        if self._write(addr, data):
            self.mem_status.set_text(f"Wrote {len(data)} byte(s) at ${addr:04X}")
            entry.set_text("")

    # ---------------------------------------------------------------- registers
    def _set_register(self, name: str, value: int) -> bool:
        s = self.session
        if not s or s.running:
            return False
        try:
            s.set_register(name, value)
        except (OSError, MonitorError) as e:
            self.state_label.set_text(f"Couldn't set {name}: {e}")
            return False
        self._on_stopped(s, value if name == "PC" else self._regs.get("PC", 0), snapshot=False)
        return True

    def _register_entered(self, entry, name: str):
        try:
            value = parse_register(name, entry.get_text(), self._symbols_by_name())
        except ValueError_ as e:
            self.state_label.set_text(str(e))
            self._show_registers()
            return
        if self._set_register(name, value):
            self.state_label.set_text(f"{name} set to ${value:0{4 if name == 'PC' else 2}X}")

    def _register_key(self, _c, keyval, _code, _state, name: str):
        from gi.repository import Gdk
        if keyval == Gdk.KEY_Escape:
            self._show_registers()
            return True
        return False

    def _flag_toggled(self, button, bit: int):
        if self._updating:
            return
        fl = self._regs.get("FL", 0)
        fl = fl | (1 << bit) if button.get_active() else fl & ~(1 << bit)
        self._set_register("FL", fl & 0xFF)
