"""Debugger: runs the program in VICE with the binary monitor and shows registers, code and memory."""
from __future__ import annotations

import threading
from pathlib import Path

import gi

gi.require_version("Gtk", "4.0")
from gi.repository import GLib, GObject, Gtk  # noqa: E402

from ..asm.disasm import disassemble  # noqa: E402
from ..emu import vice  # noqa: E402
from ..emu.binmon import EVT_JAM, EVT_RESUMED, EVT_STOPPED, BinaryMonitor, MonitorError  # noqa: E402


class DebugSession(GObject.Object):
    """Owns the VICE process and monitor connection. Signals are emitted on the GTK main thread."""

    __gsignals__ = {
        "connected": (GObject.SignalFlags.RUN_FIRST, None, ()),
        "stopped": (GObject.SignalFlags.RUN_FIRST, None, (int,)),
        "resumed": (GObject.SignalFlags.RUN_FIRST, None, ()),
        "ended": (GObject.SignalFlags.RUN_FIRST, None, (str,)),
    }

    def __init__(self, prg: Path, labels: Path | None, srcmap: dict[int, tuple[str, int]],
                 symbols: dict[int, str], emulator: str, extra_args: list[str]):
        super().__init__()
        self.prg, self.labels, self.srcmap, self.symbols = prg, labels, srcmap, symbols
        self.emulator, self.extra_args = emulator, extra_args
        self.monitor = BinaryMonitor(self._on_event)
        self.proc = None
        self.running = False
        self.checkpoints: dict[int, int] = {}  # address -> checkpoint id
        # (file, line) -> first address generated by that line
        self.line_addr: dict[tuple[str, int], int] = {}
        for addr in sorted(srcmap):
            f, ln = srcmap[addr]
            self.line_addr.setdefault((str(Path(f).resolve()), ln), addr)

    def start(self, breakpoints: list[int]):
        port = vice.free_port()
        self.proc = vice.launch(self.prg, self.emulator, self.labels, port, self.extra_args)

        def connect():
            if not vice.wait_for_port(port, 15):
                GLib.idle_add(self.emit, "ended", "VICE didn't open its monitor port")
                return
            try:
                self.monitor.connect(port=port)
                for a in breakpoints:
                    self.checkpoints[a] = self.monitor.add_checkpoint(a).id
                self.monitor.resume()
                self.running = True
            except (OSError, MonitorError) as e:
                GLib.idle_add(self.emit, "ended", f"Couldn't talk to VICE: {e}")
                return
            GLib.idle_add(self.emit, "connected")
        threading.Thread(target=connect, daemon=True).start()

    def _on_event(self, etype: int, body: bytes):
        if etype == EVT_STOPPED and len(body) >= 2:
            pc = body[0] | (body[1] << 8)
            self.running = False
            GLib.idle_add(self.emit, "stopped", pc)
        elif etype == EVT_RESUMED:
            self.running = True
            GLib.idle_add(self.emit, "resumed")
        elif etype == EVT_JAM and len(body) >= 2:
            self.running = False
            GLib.idle_add(self.emit, "stopped", body[0] | (body[1] << 8))
        elif etype == -1:
            GLib.idle_add(self.emit, "ended", "VICE exited")

    def address_for_line(self, file: str, line: int) -> int | None:
        """Address of the first code at or after `line` in `file` (within 20 lines)."""
        f = str(Path(file).resolve())
        for ln in range(line, line + 20):
            a = self.line_addr.get((f, ln))
            if a is not None:
                return a
        return None

    def set_breakpoints(self, addresses: set[int]):
        if not self.monitor.connected:
            return
        for a in list(self.checkpoints):
            if a not in addresses:
                self.monitor.delete_checkpoint(self.checkpoints.pop(a))
        for a in addresses:
            if a not in self.checkpoints:
                self.checkpoints[a] = self.monitor.add_checkpoint(a).id
        if self.running:
            self.monitor.resume()

    def cmd(self, fn, *args):
        try:
            return fn(*args)
        except (OSError, MonitorError) as e:
            self.emit("ended", str(e))

    def stop(self):
        if self.monitor.connected:
            self.monitor.quit()
            self.monitor.close()
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()


class DebuggerPanel(Gtk.Box):
    """Bottom-panel page with run controls, registers, disassembly and memory."""

    __gsignals__ = {"show-source": (GObject.SignalFlags.RUN_FIRST, None, (str, int))}

    def __init__(self):
        super().__init__(orientation=Gtk.Orientation.VERTICAL, spacing=4)
        self.session: DebugSession | None = None
        bar = Gtk.Box(spacing=4, margin_start=6, margin_top=4)
        self.append(bar)
        self.buttons = {}
        for key, icon, tip in [("continue", "media-playback-start-symbolic", "Continue (F8)"),
                               ("pause", "media-playback-pause-symbolic", "Pause"),
                               ("into", "go-down-symbolic", "Step into (F11)"),
                               ("over", "go-next-symbolic", "Step over (F10)"),
                               ("out", "go-up-symbolic", "Step out (Shift+F11)"),
                               ("stop", "media-playback-stop-symbolic", "Stop debugging")]:
            b = Gtk.Button(icon_name=icon, tooltip_text=tip, sensitive=False)
            b.connect("clicked", lambda _b, k=key: self.do(k))
            bar.append(b)
            self.buttons[key] = b
        self.state_label = Gtk.Label(label="Not debugging", css_classes=["dim-label"], margin_start=12)
        bar.append(self.state_label)

        body = Gtk.Paned(orientation=Gtk.Orientation.HORIZONTAL, vexpand=True)
        self.append(body)
        left = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=4, margin_start=6)
        self.regs = Gtk.Label(xalign=0, selectable=True, css_classes=["monospace"])
        left.append(self.regs)
        self.disasm = Gtk.TextView(editable=False, monospace=True, cursor_visible=False)
        self.disasm_pc_tag = self.disasm.get_buffer().create_tag("pc", background="rgba(255,200,0,0.35)")
        left.append(Gtk.ScrolledWindow(child=self.disasm, vexpand=True, min_content_width=360))
        body.set_start_child(left)

        right = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=4, margin_end=6)
        mbar = Gtk.Box(spacing=4)
        mbar.append(Gtk.Label(label="Memory $"))
        self.mem_addr = Gtk.Entry(text="0400", max_length=4, width_chars=6)
        self.mem_addr.connect("activate", lambda *_: self.refresh_memory())
        mbar.append(self.mem_addr)
        rb = Gtk.Button(icon_name="view-refresh-symbolic", tooltip_text="Refresh memory")
        rb.connect("clicked", lambda *_: self.refresh_memory())
        mbar.append(rb)
        right.append(mbar)
        self.memory = Gtk.TextView(editable=False, monospace=True, cursor_visible=False)
        right.append(Gtk.ScrolledWindow(child=self.memory, vexpand=True))
        body.set_end_child(right)

    # ---------------------------------------------------------------- session wiring
    def attach(self, session: DebugSession):
        self.session = session
        session.connect("connected", lambda *_: self._set_running(True))
        session.connect("stopped", self._on_stopped)
        session.connect("resumed", lambda *_: self._set_running(True))
        session.connect("ended", self._on_ended)
        self.state_label.set_text("Starting VICE…")

    def _set_running(self, running: bool):
        self.state_label.set_text("Running" if running else "Stopped")
        self.buttons["continue"].set_sensitive(not running)
        self.buttons["pause"].set_sensitive(running)
        for k in ("into", "over", "out"):
            self.buttons[k].set_sensitive(not running)
        self.buttons["stop"].set_sensitive(True)

    def _on_ended(self, _s, reason: str):
        self.state_label.set_text(f"Ended: {reason}")
        for b in self.buttons.values():
            b.set_sensitive(False)
        if self.session:
            self.session.stop()
        self.session = None
        self.emit("show-source", "", 0)

    def do(self, key: str):
        s = self.session
        if not s:
            return
        m = s.monitor
        if key == "continue":
            s.cmd(m.resume)
        elif key == "pause":
            s.cmd(m.ping)  # any command stops VICE in the monitor
            s.running = False
            regs = s.cmd(m.get_registers)
            if regs:
                self._on_stopped(s, regs.get("PC", 0))
        elif key == "into":
            s.cmd(m.step, 1, False)
        elif key == "over":
            s.cmd(m.step, 1, True)
        elif key == "out":
            s.cmd(m.step_out)
        elif key == "stop":
            self._on_ended(s, "stopped by user")

    def _on_stopped(self, session, pc: int):
        self._set_running(False)
        m = session.monitor
        regs = session.cmd(m.get_registers) or {}
        fl = regs.get("FL", 0)
        flags = "".join(c if fl & (0x80 >> i) else "." for i, c in enumerate("NV-BDIZC"))
        self.regs.set_markup(
            f"<tt><b>PC</b> ${regs.get('PC', pc):04X}  <b>A</b> ${regs.get('A', 0):02X}  <b>X</b> ${regs.get('X', 0):02X}"
            f"  <b>Y</b> ${regs.get('Y', 0):02X}  <b>SP</b> ${regs.get('SP', 0):02X}  <b>NV-BDIZC</b> {flags}</tt>")
        start = max(0, pc - 16)
        mem = session.cmd(m.read_memory, start, min(0xFFFF, pc + 96)) or b""
        # Resync: disassemble from a point that lands exactly on PC.
        lines = None
        for back in range(0, 17):
            off = pc - start - back
            if off < 0:
                break
            cand = disassemble(mem[off:], pc - back, 40, session.symbols)
            if any(a == pc for a, _, _ in cand):
                lines = cand
                break
        lines = lines or disassemble(mem[pc - start:], pc, 40, session.symbols)
        buf = self.disasm.get_buffer()
        text, pc_line = [], 0
        for i, (a, hx, t) in enumerate(lines):
            label = session.symbols.get(a, "")
            if a == pc:
                pc_line = i
            text.append(f"{'>' if a == pc else ' '} {a:04X}  {hx:<9} {t:<24} {label}")
        buf.set_text("\n".join(text))
        ok, it = buf.get_iter_at_line(pc_line)
        if ok:
            end = it.copy()
            end.forward_to_line_end()
            buf.apply_tag(self.disasm_pc_tag, it, end)
            GLib.idle_add(lambda: (self.disasm.scroll_to_iter(it, 0.1, False, 0, 0), False)[1])
        self.refresh_memory()
        src = session.srcmap.get(pc)
        if src:
            self.emit("show-source", src[0], src[1])

    def refresh_memory(self):
        s = self.session
        if not s or s.running:
            return
        try:
            addr = int(self.mem_addr.get_text().strip().lstrip("$") or "0", 16) & 0xFFFF
        except ValueError:
            return
        end = min(0xFFFF, addr + 255)
        data = s.cmd(s.monitor.read_memory, addr, end) or b""
        rows = []
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            hx = " ".join(f"{b:02X}" for b in chunk)
            asc = "".join(chr(b) if 32 <= b < 127 else "." for b in chunk)
            rows.append(f"{addr + i:04X}  {hx:<47}  {asc}")
        self.memory.get_buffer().set_text("\n".join(rows))
