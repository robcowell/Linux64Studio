REGISTERS = [("PC", 4), ("A", 2), ("X", 2), ("Y", 2), ("SP", 2)]


class DebugSession(GObject.Object):
    """Owns the VICE process and monitor connection. Signals are emitted on the GTK main thread."""

    __gsignals__ = {
        "connected": (GObject.SignalFlags.RUN_FIRST, None, ()),
        "stopped": (GObject.SignalFlags.RUN_FIRST, None, (int,)),
        "resumed": (GObject.SignalFlags.RUN_FIRST, None, ()),
        "ended": (GObject.SignalFlags.RUN_FIRST, None, (str,)),
    }

    def __init__(self, prg: Path, labels: Path | None, srcmap: dict[int, tuple[str, int]],
                 symbols: dict[int, str], emulator: str, extra_args: list[str], c_lines: list | None = None,
                 asm_lines: list | None = None):
        super().__init__()
        # C builds: which C line each address belongs to, for stepping by C line (step_line)
        self.lines = LineTable(c_lines or [])
        self.asm_lines = LineTable(asm_lines or [])       # the project's own .s files: stepped by instruction
        self.stepping = False
        self._cancel_step = False
        self.prg, self.labels, self.srcmap, self.symbols = prg, labels, srcmap, symbols
        self.emulator, self.extra_args = emulator, extra_args
        self.monitor = BinaryMonitor(self._on_event)
        self.proc = None
        self.running = False
        # Every stop and resume VICE reports gets the next number. A stop that a resume has
        # overtaken by the time the main loop handles it (such as the brief stops while
        # breakpoints are set at start-up) is out of date and ignored.
        self.event_seq = 0
        # While connecting and setting breakpoints, VICE stops briefly for each command. Those
        # stops are never shown, whatever order VICE's events arrive in.
        self.starting = True
        # VICE 3.7.1 ignores the first step after a register write, and if a breakpoint is
        # active at the PC meanwhile, the step after that stops on it without running anything.
        # Whether this VICE does it is found out at start-up; if so, set_register() takes the
        # ignored step itself, unseen, with any breakpoint at the PC switched off.
        self.regset_swallows_step = False
        self._quiet = False
        self._quiet_stop = threading.Event()
        self.checkpoints: dict[int, int] = {}  # address -> checkpoint id
        # From the source (CBM prg Studio's BREAKPOINT, DEBUGSTARTADDRESS and WATCH directives):
        self.source_breakpoints: set[int] = set()          # kept whatever the editor's gutter says
        self.conditions: dict[int, str] = {}               # address -> VICE condition, e.g. "X == $14"
        self.watches: list[tuple[str, int, str]] = []       # (name, address, comment)
        # (file, line) -> first address generated by that line
        self.line_addr: dict[tuple[str, int], int] = {}
        for addr in sorted(srcmap):
            f, ln = srcmap[addr]
            self.line_addr.setdefault((str(Path(f).resolve()), ln), addr)

    def start(self, breakpoints: list[int]):
        port = vice.free_port()
        self.proc = vice.launch(self.prg, self.emulator, self.labels, port, self.extra_args)

        def connect():
            if not vice.wait_for_port(port, 15):
                GLib.idle_add(self.emit, "ended", "VICE didn't open its monitor port")
                return
            try:
                self.monitor.connect(port=port)
                self._calibrate()
                for a in sorted(set(breakpoints) | self.source_breakpoints):
                    self.checkpoints[a] = self.monitor.add_checkpoint(a).id
                    if a in self.conditions:
                        self.monitor.set_condition(self.checkpoints[a], self.conditions[a])
                self.monitor.resume()
                self.running = True
                self.event_seq += 1   # anything VICE reported before this is out of date
                self.starting = False
            except (OSError, MonitorError) as e:
                GLib.idle_add(self.emit, "ended", f"Couldn't talk to VICE: {e}")
                return
            GLib.idle_add(self.emit, "connected")
        threading.Thread(target=connect, daemon=True).start()

    def _calibrate(self):
        """Find out whether a step after a register write is ignored, while the KERNAL is still
        resetting (so an extra instruction there makes no difference)."""
        m = self.monitor
        before = m.get_registers()
        m.set_register("A", before.get("A", 0))   # writes the value it already has
        m.step(1)
        time.sleep(0.05)
        self.regset_swallows_step = m.get_registers().get("PC") == before.get("PC")

    def set_register(self, name: str, value: int) -> None:
        m = self.monitor
        if not self.regset_swallows_step:
            m.set_register(name, value)
            return
        pc = value if name == "PC" else m.get_registers().get("PC")
        cid = self.checkpoints.get(pc)
        if cid is not None:
            m.enable_checkpoint(cid, False)
        try:
            m.set_register(name, value)
            self._quiet_stop.clear()
            self._quiet = True
            try:
                m.step(1)                      # the step VICE ignores; nothing runs
                self._quiet_stop.wait(1.0)
            finally:
                self._quiet = False
        finally:
            if cid is not None:
                m.enable_checkpoint(cid, True)

    def snapshot_memory(self) -> bytes:
        """All 64K as the CPU sees it now. A running program pauses for the read and carries on,
        without the debugger showing a stop."""
        if self.stepping:
            raise MonitorError("the debugger is stepping by C line: try again when it stops")
        m = self.monitor
        was_running = self.running
        if was_running:
            self._quiet_stop.clear()
            self._quiet = True
        try:
            # A response holds at most $FFFF bytes, so read in two halves.
            data = m.read_memory(0x0000, 0x7FFF) + m.read_memory(0x8000, 0xFFFF)
        finally:
            if was_running:
                try:
                    m.resume()
                finally:
                    self._quiet = False
        return data

    def save_snapshot(self, path) -> int:
        """Snapshot the machine to a .vsf. A running program carries on afterwards. Returns the PC."""
        if self.stepping:
            raise MonitorError("the debugger is stepping by C line: try again when it stops")
        m = self.monitor
        was_running = self.running
        if was_running:
            self._quiet_stop.clear()
            self._quiet = True
        try:
            m.dump(str(path))
            pc = m.get_registers().get("PC", 0)
        finally:
            if was_running:
                try:
                    m.resume()
                finally:
                    self._quiet = False
        return pc

    def restore_snapshot(self, path) -> int:
        """Load a .vsf and stop there, so the debugger shows the machine as it was."""
        m = self.monitor
        self._quiet = True
        try:
            pc = m.undump(str(path))
        finally:
            self._quiet = False
        self.running = False
        self.event_seq += 1
        GLib.idle_add(self._deliver_stop, pc, self.event_seq)
        return pc

    def _on_event(self, etype: int, body: bytes):
        if self._quiet:
            if etype in (EVT_STOPPED, EVT_JAM):
                self._quiet_stop.set()
            return
        if etype in (EVT_STOPPED, EVT_JAM) and len(body) >= 2:
            if self.starting:
                return
            pc = body[0] | (body[1] << 8)
            self.running = False
            self.event_seq += 1
            seq = self.event_seq
            GLib.idle_add(self._deliver_stop, pc, seq)
        elif etype == EVT_RESUMED:
            if self.starting:
                return
            self.running = True
            self.event_seq += 1
            GLib.idle_add(self.emit, "resumed")
        elif etype == -1:
            GLib.idle_add(self.emit, "ended", "VICE exited")

    def _deliver_stop(self, pc: int, seq: int):
        if seq == self.event_seq and not self.running:
            self.emit("stopped", pc)
        return False

    def address_for_line(self, file: str, line: int) -> int | None:
        """Address of the first code at or after `line` in `file` (within 20 lines)."""
        f = str(Path(file).resolve())
        for ln in range(line, line + 20):
            a = self.line_addr.get((f, ln))
            if a is not None:
                return a
        return None

    def set_breakpoints(self, addresses: set[int]):
        if not self.monitor.connected:
            return
        addresses = set(addresses) | self.source_breakpoints
        for a in list(self.checkpoints):
            if a not in addresses:
                self.monitor.delete_checkpoint(self.checkpoints.pop(a))
        for a in addresses:
            if a not in self.checkpoints:
                self.checkpoints[a] = self.monitor.add_checkpoint(a).id
                if a in self.conditions:
                    self.monitor.set_condition(self.checkpoints[a], self.conditions[a])
        if self.running:
            self.monitor.resume()

    def leave_breakpoint(self, pc: int) -> None:
        """Run the instruction at pc with its breakpoint off.

        After registers are changed, VICE fires an exec breakpoint at the current PC again
        before running anything, so stepping or continuing from a breakpoint would go nowhere.
        """
        cid = self.checkpoints.get(pc)
        if cid is None:
            return
        m = self.monitor
        m.enable_checkpoint(cid, False)
        try:
            m.step(1, False)
        finally:
            m.enable_checkpoint(cid, True)

    # ---------------------------------------------------------------- stepping by C line
    def c_line_at(self, pc: int) -> tuple[str, int] | None:
        return self.lines.line_at(pc) if self.lines else None

    def steps_by_c_line(self, pc: int) -> bool:
        """In a C program, F10/F11 step by C line on a line of C, and from code with no line at all
        (cc65's runtime, the KERNAL) they run on to the next line of C. In the project's own assembler
        (.s files) they step by instruction."""
        if not self.lines:
            return False
        return self.lines.line_at(pc) is not None or self.asm_lines.line_at(pc) is None

    def step_line(self, over: bool) -> None:
        """Step Over / Step Into by C line (see emu.clines): runs on a thread, since a line can take
        any time (waiting for a key, say), and reports the stop as any other. Pause cancels it."""
        self.stepping, self._cancel_step = True, False
        self.running = True
        self.event_seq += 1
        GLib.idle_add(self.emit, "resumed")
        threading.Thread(target=self._step_line, args=(over,), daemon=True).start()

    def cancel_step(self) -> None:
        self._cancel_step = True

    def _wait_quiet(self) -> bool:
        """Wait for VICE to stop (quietly); False if the step was cancelled meanwhile."""
        while not self._quiet_stop.wait(0.1):
            if self._cancel_step or not self.monitor.connected:
                return False
        return True

    def _step_line(self, over: bool):
        m = self.monitor
        temp: list[int] = []
        pc = None
        self._quiet = True
        try:
            regs = m.get_registers()
            pc, sp = regs.get("PC", 0), regs.get("SP", 0)
            start, start_sp = self.lines.line_at(pc), sp
            if pc in self.checkpoints:
                # VICE would stop on this breakpoint again before running anything: leave it first
                cid = self.checkpoints[pc]
                m.enable_checkpoint(cid, False)
                try:
                    self._quiet_stop.clear()
                    m.step(1, False)
                    self._wait_quiet()
                finally:
                    m.enable_checkpoint(cid, True)
            for _round in range(10000):              # (each round runs at full speed: this is plenty)
                regs = m.get_registers()
                pc, sp = regs.get("PC", 0), regs.get("SP", 0)
                action = decide(self.lines, start, start_sp, pc, sp, over,
                                at_user_breakpoint=_round > 0 and pc in self.checkpoints)
                if action == STOP or self._cancel_step:
                    break
                self._quiet_stop.clear()
                if action == RUN:
                    temp = [m.add_checkpoint(a, b).id for a, b in self.lines.ranges_outside(start)]
                    m.resume()
                elif action == FINISH:
                    m.step_out()
                if not self._wait_quiet():
                    m.ping()                         # cancelled: stop VICE where it is
                for cid in temp:
                    m.delete_checkpoint(cid)
                temp = []
                if self._cancel_step:
                    break
            pc = m.get_registers().get("PC", pc or 0)
        except (OSError, MonitorError) as e:
            GLib.idle_add(self.emit, "ended", f"Couldn't step: {e}")
            return
        finally:
            for cid in temp:
                try:
                    m.delete_checkpoint(cid)
                except (OSError, MonitorError):
                    pass
            self._quiet = False
            self.stepping = False
        self.running = False
        self.event_seq += 1
        GLib.idle_add(self._deliver_stop, pc, self.event_seq)

    def cmd(self, fn, *args):
        try:
            return fn(*args)
        except (OSError, MonitorError) as e:
            self.emit("ended", str(e))

    def stop(self):
        if self.monitor.connected:
            self.monitor.quit()
            self.monitor.close()
        if self.proc and self.proc.poll() is None:
            self.proc.terminate()


